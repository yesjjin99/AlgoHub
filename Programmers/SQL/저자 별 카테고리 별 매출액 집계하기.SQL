WITH PRE_BOOK_SALES AS (
    SELECT B.BOOK_ID, B.CATEGORY, B.AUTHOR_ID, SUM(B.PRICE * S.SALES) AS TOTAL_SALES
    FROM BOOK B JOIN BOOK_SALES S
    USING (BOOK_ID)
    WHERE SALES_DATE LIKE '2022-01%'
    GROUP BY B.AUTHOR_ID, B.CATEGORY
)

SELECT P.AUTHOR_ID, A.AUTHOR_NAME, P.CATEGORY, P.TOTAL_SALES
FROM PRE_BOOK_SALES P JOIN AUTHOR A
USING (AUTHOR_ID)
ORDER BY P.AUTHOR_ID, P.CATEGORY DESC;